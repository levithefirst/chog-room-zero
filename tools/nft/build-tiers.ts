// Writes src/nft/tier-table.ts from the verified catalogue: one letter per metadata id (C, U, R, E, L) and the ten 1:1 ids.
// The game server and the Vercel functions read tier from this table after a chain read gives them the metadata id, so
// nothing at play time depends on IPFS or a marketplace. Rerun after any catalogue change:  node tools/nft/build-tiers.ts
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const cat = JSON.parse(readFileSync(new URL('data/chog-genesis/catalogue.json', root), 'utf8')) as {
  records: { tokenId: number; metadataId: number; traits: Record<string, string>; specialName: string | null }[];
};
const LETTER: Record<string, string> = { Common: 'C', Uncommon: 'U', Rare: 'R', Epic: 'E', Legendary: 'L' };
const byMeta = new Map(cat.records.map((r) => [r.metadataId, r]));
let table = '';
for (let m = 1; m <= 1969; m++) {
  const r = byMeta.get(m);
  const l = r && LETTER[r.traits.Tier];
  if (!l) throw new Error(`metadata id ${m}: missing record or unknown tier`);
  table += l;
}
const oneOfOne = cat.records.filter((r) => r.traits.Base === '1:1').map((r) => r.metadataId).sort((a, b) => a - b);
if (oneOfOne.length !== 10) throw new Error(`expected 10 one-of-one tokens, found ${oneOfOne.length}`);
const out = `// GENERATED by tools/nft/build-tiers.ts from data/chog-genesis/catalogue.json. Do not edit by hand.
// TIER_TABLE[metadataId - 1] is the token's Tier trait: C Common, U Uncommon, R Rare, E Epic, L Legendary.
export const TIER_TABLE =
  '${table.match(/.{1,120}/g)!.join("' +\n  '")}';
/** Metadata ids of the ten 1:1 (Base "1:1") tokens. Each has a signature ability (src/config/power.ts). */
export const ONE_OF_ONE_IDS = [${oneOfOne.join(', ')}] as const;
`;
writeFileSync(new URL('src/nft/tier-table.ts', root), out);
console.log(`wrote src/nft/tier-table.ts: ${table.length} ids, 1:1 = ${oneOfOne.join(', ')}`);
