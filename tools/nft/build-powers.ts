// Writes src/nft/power-table.ts from the verified catalogue: which CHOG superpowers each token's REAL traits carry
// (owner 2026-10-18 CHOG SUPERPOWER SYSTEM). The game server reads it after a verified chain read gives it the metadata
// id, so a power comes only from the token's own metadata. Rerun after any catalogue change:  node tools/nft/build-powers.ts
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const cat = JSON.parse(readFileSync(new URL('data/chog-genesis/catalogue.json', root), 'utf8')) as {
  records: { metadataId: number; traits: Record<string, string> }[];
};
// Trait value -> power family. Exact metadata strings (spelling and case as on chain). See docs/design/superpowers.md.
const FAMILY: { power: string; bit: number; category: string; values: string[] }[] = [
  { power: 'laser', bit: 1, category: 'Eyes', values: ['Purple laser', 'fire laser', 'Green laser', 'cyan laser'] },
  { power: 'laser', bit: 1, category: 'Head', values: ['Blue Laser'] },
  { power: 'xray', bit: 2, category: 'Eyes', values: ['Gradient visor', 'Sunset visor', 'Plasma visor'] },
  { power: 'bubble', bit: 4, category: 'Mouth', values: ['Bubblegum'] },
  { power: 'drool', bit: 8, category: 'Mouth', values: ['Drooling'] },
  { power: 'aura', bit: 16, category: 'Aura', values: ['*'] },
];
const DIGITS = '0123456789abcdefghijklmnopqrstuv';
const byMeta = new Map(cat.records.map((r) => [r.metadataId, r]));
let table = '';
for (let m = 1; m <= 1969; m++) {
  const r = byMeta.get(m);
  if (!r) throw new Error(`metadata id ${m}: missing record`);
  let mask = 0;
  for (const f of FAMILY) {
    const v = r.traits[f.category];
    if (v !== undefined && (f.values[0] === '*' || f.values.includes(v))) mask |= f.bit;
  }
  table += DIGITS[mask];
}
const out = `// GENERATED by tools/nft/build-powers.ts from data/chog-genesis/catalogue.json. Do not edit by hand.
// POWER_TABLE[metadataId - 1] is a base-32 digit: the bit mask of CHOG superpowers the token's traits carry
// (1 Laser: laser Eyes or the Blue Laser head; 2 X-Ray: visor Eyes; 4 Bubble: Bubblegum mouth; 8 Drool: Drooling mouth;
// 16 Aura: any Aura).
export const POWER_TABLE =
  '${table.match(/.{1,120}/g)!.join("' +\n  '")}';
/** The exact trait values behind each power (documentation and tests). */
export const POWER_TRAITS = ${JSON.stringify(FAMILY.map(({ power, category, values }) => ({ power, category, values })), null, 2).replace(/"(\w+)":/g, '$1:')} as const;
`;
writeFileSync(new URL('src/nft/power-table.ts', root), out);
console.log(`wrote src/nft/power-table.ts: ${table.length} ids, ${[...table].filter((c) => c !== '0').length} with a power`);
