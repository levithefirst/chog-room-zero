// Writes src/nft/trait-table.ts from the verified catalogue: each token's real traits, for the YOUR CHOG card (owner
// 2026-10-18: "Show YOUR CHOG, CHOG #XXX, [actual traits], ABILITY, TRAIT"). Per category a dictionary of the exact
// metadata values, and per token two base-64 digits per category (0 = the token has none). Rerun after any catalogue
// change:  node --experimental-strip-types tools/nft/build-traits.ts
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const cat = JSON.parse(readFileSync(new URL('data/chog-genesis/catalogue.json', root), 'utf8')) as { records: { metadataId: number; traits: Record<string, string> }[] };
// Shown in this order; Tier is shown as the rarity badge, so it is left out here.
const CATS = ['Base', 'Background', 'Skin', 'Body', 'Head', 'Eyes', 'Mouth', 'Accessory', 'Aura', 'Side', 'Form', 'Naked'];
const D = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ-_';
const byMeta = new Map(cat.records.map((r) => [r.metadataId, r]));
const dict: Record<string, string[]> = {};
for (const c of CATS) dict[c] = [...new Set(cat.records.map((r) => r.traits[c]).filter((v): v is string => v !== undefined))].sort();
const cols: Record<string, string> = {};
for (const c of CATS) {
  let s = '';
  for (let m = 1; m <= 1969; m++) {
    const v = byMeta.get(m)?.traits[c];
    const i = v === undefined ? 0 : dict[c].indexOf(v) + 1;
    if (i >= 64 * 64) throw new Error(`${c}: too many values`);
    s += D[Math.floor(i / 64)] + D[i % 64];
  }
  cols[c] = s;
}
const out = `// GENERATED by tools/nft/build-traits.ts from data/chog-genesis/catalogue.json. Do not edit by hand.
// TRAIT_VALUES[category] lists the exact metadata values; TRAIT_COLUMNS[category] holds two base-64 digits per token
// (metadataId 1 first): 0 = no such trait, n = TRAIT_VALUES[category][n - 1].
export const TRAIT_CATEGORIES = ${JSON.stringify(CATS)} as const;
export const TRAIT_VALUES: Record<string, readonly string[]> = ${JSON.stringify(dict)};
export const TRAIT_COLUMNS: Record<string, string> = ${JSON.stringify(cols)};
`;
writeFileSync(new URL('src/nft/trait-table.ts', root), out);
console.log(`wrote src/nft/trait-table.ts: ${CATS.length} categories, ${out.length} chars`);
